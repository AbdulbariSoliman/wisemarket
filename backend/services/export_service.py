# ── QR Code ───────────────────────────────────────────────────

def _make_qr(data: str, size_mm: int = 25) -> Image:
    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_L,
        box_size=4,
        border=2,
    )
    qr.add_data(data)
    qr.make(fit=True)
    img = qr.make_image(fill_color="black", back_color="white")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return Image(buf, width=size_mm * mm, height=size_mm * mm)


# ── Badge builder ─────────────────────────────────────────────

def _badge_text(ontology_tags: Dict, lang: str, t: Dict) -> str:
    if not ontology_tags:
        return ""
    badge_map = t["badges"]
    badges = []
    for key, label in badge_map.items():
        if ontology_tags.get(key):
            badges.append(label)
    return "  ".join(badges)


# ── Name resolver ─────────────────────────────────────────────

def _get_name(item: Dict, lang: str) -> str:
    return (
        item.get(f"name_{lang}")
        or item.get("name_en")
        or item.get("name_de")
        or item.get("product_name")
        or item.get("name")
        or "Unknown"
    )


# ── Main export function ──────────────────────────────────────

def generate_shopping_list_pdf(
    items: List[Dict],
    lang: str = "en",
    store_filter: Optional[str] = None,
    list_name: Optional[str] = None,
    cheapest_store: Optional[str] = None,
    basket_totals: Optional[Dict[str, float]] = None,
    qr_url: Optional[str] = None,
) -> bytes:
    """
    Generate a multilingual shopping list PDF.

    Parameters
    ----------
    items : list of dicts, each containing:
        - gtin, name_en/de/fr/it or name, brand, category
        - quantity, store, price_chf
        - ontology_tags (dict of dietary flags)
        - price_per_100g (optional)
    lang : "en" | "de" | "fr" | "it"
    store_filter : if set, show prices for this store only
    list_name : custom list title
    cheapest_store : highlight this store as cheapest
    basket_totals : {store: total_chf}
    qr_url : URL to encode as QR code

    Returns
    -------
    bytes — PDF file content
    """
    if lang not in TRANSLATIONS:
        lang = "en"
    t = TRANSLATIONS[lang]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        rightMargin=15 * mm,
        leftMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        title=list_name or t["title"],
        author="WiseMarket",
    )

    W = A4[0] - 30 * mm  # usable width

    # ── Styles ────────────────────────────────────────────────
    styles = getSampleStyleSheet()

    s_title = ParagraphStyle(
        "wm_title",
        parent=styles["Title"],
        fontSize=22,
        textColor=BRAND_DARK,
        spaceAfter=4,
        fontName="Helvetica-Bold",
    )
    s_subtitle = ParagraphStyle(
        "wm_subtitle",
        parent=styles["Normal"],
        fontSize=9,
        textColor=BRAND_GRAY,
        spaceAfter=2,
        fontName="Helvetica",
    )
    s_section = ParagraphStyle(
        "wm_section",
        parent=styles["Heading2"],
        fontSize=11,
        textColor=BRAND_DARK,
        spaceBefore=8,
        spaceAfter=4,
        fontName="Helvetica-Bold",
        borderPad=2,
    )
    s_item = ParagraphStyle(
        "wm_item",
        parent=styles["Normal"],
        fontSize=9,
        textColor=BRAND_DARK,
        fontName="Helvetica-Bold",
        leading=12,
    )
    s_small = ParagraphStyle(
        "wm_small",
        parent=styles["Normal"],
        fontSize=7.5,
        textColor=BRAND_GRAY,
        fontName="Helvetica",
        leading=10,
    )
    s_badge = ParagraphStyle(
        "wm_badge",
        parent=styles["Normal"],
        fontSize=7,
        textColor=colors.white,
        fontName="Helvetica-Bold",
        leading=9,
    )
    s_total = ParagraphStyle(
        "wm_total",
        parent=styles["Normal"],
        fontSize=10,
        textColor=BRAND_DARK,
        fontName="Helvetica-Bold",
        spaceAfter=2,
    )
    s_footer = ParagraphStyle(
        "wm_footer",
        parent=styles["Normal"],
        fontSize=7,
        textColor=BRAND_GRAY,
        fontName="Helvetica",
        alignment=1,
    )

    story = []

    # ── Header ────────────────────────────────────────────────
    title_text = list_name or t["title"]
    store_label = store_filter.capitalize() if store_filter else t["all_stores"]
    today = date.today().strftime("%d.%m.%Y")

    # Header table: title left, QR right
    header_content = [
        [
            [
                Paragraph(f"🛒 {title_text}", s_title),
                Paragraph(
                    f"{t['date']}: {today}  |  {t['store']}: {store_label}",
                    s_subtitle,
                ),
            ],
            _make_qr(qr_url or "https://wisemarket.ch", 22) if qr_url else Spacer(1, 1),
        ]
    ]
    header_table = Table(
        header_content,
        colWidths=[W - 28 * mm, 28 * mm],
    )
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN",  (1, 0), (1, 0),  "RIGHT"),
        ("LEFTPADDING",  (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 0),
        ("TOPPADDING",   (0, 0), (-1, -1), 0),
    ]))
    story.append(header_table)
    story.append(HRFlowable(
        width=W, thickness=2, color=BRAND_RED, spaceAfter=6
    ))

    # ── Group items by category ───────────────────────────────
    grouped: Dict[str, List[Dict]] = {}
    for item in items:
        cat = item.get("category") or "other"
        if cat not in grouped:
            grouped[cat] = []
        grouped[cat].append(item)

    # Sort by CATEGORY_ORDER
    ordered_cats = [c for c in CATEGORY_ORDER if c in grouped]
    ordered_cats += [c for c in grouped if c not in CATEGORY_ORDER]

    grand_total = 0.0

    for cat in ordered_cats:
        cat_items = grouped[cat]
        cat_label = t["categories"].get(cat, t["categories"]["other"])

        story.append(Paragraph(cat_label, s_section))

        # Table headers
        col_widths = [W * 0.38, W * 0.14, W * 0.16, W * 0.16, W * 0.16]
        table_data = [[
            Paragraph(f"<b>{t['product']}</b>", s_small),
            Paragraph(f"<b>{t['store']}</b>",   s_small),
            Paragraph(f"<b>{t['qty']}</b>",      s_small),
            Paragraph(f"<b>{t['unit_price']}</b>", s_small),
            Paragraph(f"<b>{t['total']}</b>",    s_small),
        ]]

        for item in cat_items:
            name    = _get_name(item, lang)
            brand   = item.get("brand") or ""
            qty     = item.get("quantity", 1)
            store   = item.get("store") or store_filter or "—"
            price   = item.get("price_chf")
            tags    = item.get("ontology_tags") or {}

            # Badge string
            badges = _badge_text(tags, lang, t)

            # Name cell: name + brand + badges
            name_parts = [Paragraph(name, s_item)]
            if brand:
                name_parts.append(Paragraph(brand, s_small))
            if badges:
                name_parts.append(Paragraph(badges, s_small))

            # Price calculation
            line_total = None
            price_str = t["missing"]
            total_str = t["missing"]
            if price is not None:
                line_total = round(price * qty, 2)
                grand_total += line_total
                price_str = f"CHF {price:.2f}"
                total_str = f"CHF {line_total:.2f}"

            # Store label with colour dot
            store_color = STORE_COLORS.get(store.lower(), BRAND_GRAY)
            store_para = Paragraph(
                f'<font color="#{store_color.hexval()[2:].upper()}">'
                f'&#9632;</font> {store.capitalize()}',
                s_small,
            )

            table_data.append([
                name_parts,
                store_para,
                Paragraph(str(qty), s_small),
                Paragraph(price_str, s_small),
                Paragraph(f"<b>{total_str}</b>", s_small),
            ])

        item_table = Table(table_data, colWidths=col_widths, repeatRows=1)
        item_table.setStyle(TableStyle([
            # Header row
            ("BACKGROUND",    (0, 0), (-1, 0),  BRAND_LIGHT),
            ("LINEBELOW",     (0, 0), (-1, 0),  0.5, BRAND_GRAY),
            ("FONTNAME",      (0, 0), (-1, 0),  "Helvetica-Bold"),
            # Data rows alternating
            ("ROWBACKGROUNDS",(0, 1), (-1, -1), [colors.white, colors.HexColor("#F8F9FA")]),
            ("LINEBELOW",     (0, 1), (-1, -1), 0.3, colors.HexColor("#DEE2E6")),
            # Alignment
            ("VALIGN",        (0, 0), (-1, -1), "TOP"),
            ("ALIGN",         (2, 0), (-1, -1), "RIGHT"),
            # Padding
            ("TOPPADDING",    (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING",   (0, 0), (-1, -1), 4),
            ("RIGHTPADDING",  (0, 0), (-1, -1), 4),
            # Outer border
            ("BOX",           (0, 0), (-1, -1), 0.5, BRAND_GRAY),
        ]))
        story.append(item_table)
        story.append(Spacer(1, 4 * mm))

    # ── Totals section ────────────────────────────────────────
    story.append(HRFlowable(width=W, thickness=1, color=BRAND_GRAY, spaceAfter=4))

    totals_rows = []

    if basket_totals:
        for store, total in sorted(basket_totals.items(), key=lambda x: x[1]):
            marker = " ★" if store == cheapest_store else ""
            color_hex = STORE_COLORS.get(store, BRAND_GRAY)
            totals_rows.append([
                Paragraph(
                    f'<font color="#{color_hex.hexval()[2:].upper()}">&#9632;</font>'
                    f' {store.capitalize()}{marker}',
                    s_total,
                ),
                Paragraph(f"CHF {total:.2f}", s_total),
            ])
    else:
        totals_rows.append([
            Paragraph(t["basket_total"], s_total),
            Paragraph(f"CHF {grand_total:.2f}", s_total),
        ])

    if cheapest_store and basket_totals:
        cheapest_total = basket_totals.get(cheapest_store, 0)
        totals_rows.append([
            Paragraph(f"★ {t['cheapest']}: {cheapest_store.capitalize()}", s_small),
            Paragraph(f"<b>CHF {cheapest_total:.2f}</b>", s_small),
        ])

    totals_table = Table(totals_rows, colWidths=[W * 0.75, W * 0.25])
    totals_table.setStyle(TableStyle([
        ("ALIGN",  (1, 0), (1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING",    (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING",   (0, 0), (-1, -1), 0),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 0),
        # Highlight last total row
        ("LINEABOVE", (0, -1), (-1, -1), 1, BRAND_DARK),
        ("FONTNAME",  (0, -1), (-1, -1), "Helvetica-Bold"),
    ]))
    story.append(totals_table)

    # ── Footer ────────────────────────────────────────────────
    story.append(Spacer(1, 6 * mm))
    story.append(HRFlowable(width=W, thickness=0.5, color=BRAND_GRAY))
    story.append(Spacer(1, 2 * mm))
    story.append(Paragraph(
        f"{t['generated']}  •  wisemarket.ch  •  {today}",
        s_footer,
    ))

    doc.build(story)
    return buf.getvalue()
